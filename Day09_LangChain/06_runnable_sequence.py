
from langchain_core.prompts import PromptTemplate
from langchain_core.output_parsers import StrOutputParser

prompt = PromptTemplate.from_template(
    "Explain {topic} in one simple sentence."
)

parser = StrOutputParser()

# This is a formatting-and-parsing demonstration.
# No language model is connected.
formatted_prompt = prompt.invoke({"topic": "RAG"})

parsed_text = parser.invoke(
    "RAG retrieves relevant information to help an AI generate a grounded answer."
)

print("=== Runnable Components ===")
print("\nFormatted prompt:")
print(formatted_prompt.to_string())

print("\nParsed text:")
print(parsed_text)

print("\nNote: The prompt and parser are invoked separately.")
print("No LLM is connected, so no answer was generated by a model.")